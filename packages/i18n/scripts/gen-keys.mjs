#!/usr/bin/env node
/**
 * Writes src/keys.ts from the English catalog, so a mistyped key is a type error. Plural keys
 * (`x.one`, `x.other`…) become one key, `x`, picked with `{ count }`.
 *
 *   node scripts/gen-keys.mjs           write it
 *   node scripts/gen-keys.mjs --check   fail if it's out of date (npm run check)
 */
import { readFileSync, writeFileSync } from 'node:fs'

const PLURAL = /\.(zero|one|two|few|many|other)$/
const en = JSON.parse(readFileSync(new URL('../src/catalogs/en.json', import.meta.url), 'utf8'))
const plain = new Set()
const plural = new Set()
for (const key of Object.keys(en)) {
  if (PLURAL.test(key)) plural.add(key.replace(PLURAL, ''))
  else plain.add(key)
}
const all = [...new Set([...plain, ...plural])].sort()
const quote = (k) => `  | '${k}'`
const text = `// Generated by scripts/gen-keys.mjs from src/catalogs/en.json (npm run keys -w @cf-dam/i18n). Don't edit.

export type MessageKey =
${all.map(quote).join('\n')}

/** Keys with plural forms: pass \`{ count }\`. */
export const PLURAL_KEYS: ReadonlySet<string> = new Set([${[...plural].sort().map((k) => `'${k}'`).join(', ')}])
`
const target = new URL('../src/keys.ts', import.meta.url)
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {}
  if (current !== text) {
    console.error('i18n: src/keys.ts is out of date with en.json. Run: npm run keys -w @cf-dam/i18n')
    process.exit(1)
  }
  console.log(`i18n: ${all.length} keys, keys.ts up to date`)
} else {
  writeFileSync(target, text)
  console.log(`i18n: wrote ${all.length} keys`)
}
